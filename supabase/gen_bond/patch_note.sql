## 3.6.0 · 백년지기
연담 인물과 백년지기를 맺으면 그 사람이 내 별채에 머물며 말을 주고받습니다.

### 맺기
- 연담 다섯째 이야기를 마친 인물과 「백년지기」를 맺을 수 있습니다. 한 사람에 한 인물입니다.
- 그 인물이 있는 곳의 연담 창에서 정표 짓는 값 300전을 내고 맺습니다. 인물마다 정표가 다릅니다.
- 연리 정인이 있어도 맺을 수 있습니다.
- 끊으면 인물은 별채를 떠나고 정표는 「빛바랜 정표」로 남습니다. 친밀도와 연담 주문은 그대로이고, 하루 뒤에 다시 맺을 수 있습니다.

### 별채에서
- 백년지기는 내 별채를 걸어 다닙니다. 누르거나 아래 줄의 「말 걸기」로 하루 열 번 말을 걸 수 있습니다.
- 시간대·날씨, 내 처지(쓰러짐·침식·요화·원정에서 돌아옴·먼 길·레벨 오름), 별채의 초상·동무·새 가구, 맺은 지 이레·한 달·백 날 같은 날마다 하는 말이 다릅니다.
- 하루 한 번 선물을 건넬 수 있습니다. 그 인물 분야의 물품이면 특별히 반기고, 가끔 그 인물이 만든 물품을 답례로 줍니다.
- 머무는 방은 동무처럼 고를 수 있습니다. 혼례 정인과 한 지붕이면 두 사람의 백년지기가 함께 지냅니다.

### 정표
- 정표는 연리 정표와 같은 칸이라 한 번에 하나만 찹니다.
- 정표를 차고 그날 처음 말을 걸면 그때부터 하루 동안 회복 +5%·침식 −5%를 받습니다. 연리 효과가 켜져 있으면 겹치지 않습니다.
