## 7.5.6
- 거래소 사기 목록·내 등록에 물품 **등급**(범품·양품·진품·명품·신품)을 색 글자로 붙이고, 줄 왼쪽 띠도 등급 색으로 칠했습니다. 올릴 물품을 고르는 칸에도 등급을 적었습니다.
- 거래소 목록에 가방처럼 물품의 짧은 설명을 함께 적었고, 넓은 화면(PC)에서는 사기 목록·내 등록을 두 줄로 나눠 보이게 했습니다(한 줄이 길기만 하고 가운데가 비던 것).
- 알림음 「띠로링」을 더했습니다: 귓속말이 올 때, 채팅(전체·지역·세력·파티·모임)에서 누가 **@내 캐릭터 이름**을 쓸 때, 탐색력이 가득 찰 때, 잠깐 쉬기·푹 쉬기를 다시 할 수 있을 때(둘을 따로 켜고 끄며, 거의 같이 끝나면 한 번만 울림), 원정대가 돌아올 때, 자율 활동이 끝날 때 울립니다(디디 님 제보). 설정 › 소리의 「알림음」에서 종류마다 켜고 끌 수 있고, 효과음을 꺼도 울립니다. 게임 창을 내려 두고 다른 일을 할 때 PC에서 들립니다(휴대폰은 화면을 보고 있을 때만).
- 현장 탐색에서 요괴와 마주쳐 싸울 때 배경음악이 전투 곡으로 바뀌지 않고 그 지역 곡이 이어집니다. 원정대가 나가 있는 동안의 전투 곡은 그대로입니다.
- 조사원 카드의 「별채 구경」을 눌렀을 때 대문이 닫혔거나 벗에게만 열린 별채면, 빈 별채 화면으로 옮기지 않고 그 자리에서 알림으로 알려 줍니다.
$N$
