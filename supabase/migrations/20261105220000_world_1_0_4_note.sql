## 1.0.4 · 편의와 정리
- 이동·원정·자율 활동 중에는 그 자리에서 하는 일(상점·창고·수리·강화·거래·퀘스트 받기와 보고·의뢰·세력 일·물품 사용 등)을 할 수 없습니다. 셋 다 같은 기준이고, 그동안 해당 단추는 잠기며 까닭이 보입니다. 쓰러졌을 때 회생 부적만 예외입니다.
- 원정에서 쓰러뜨린 요괴와 채집한 것도 퀘스트·세력 할 일에 셉니다. 원정에서 돌아온 뒤에 한꺼번에 반영됩니다.
- 안전지대에서 제작할 때 창고에 둔 도구도 조건으로 인정합니다. 같은 갈래의 더 높은 단계 도구로도 됩니다.
- 물품 「얻는 곳」에 실제로 갈 수 없는 안전지대 채집터가 나오던 것을 고쳤습니다. 「외 n곳」은 물품 정보·퀘스트·도감 어디서나 같은 지역 목록 창으로 열립니다.
- 직접 거래·거래소 등록·서신 붙이기·조사원 의뢰·세력 기부에서 물품을 가방처럼 생긴 창에서 고릅니다. 직접 거래는 줄 것과 받을 것을 한눈에 봅니다.
- 긴 안내문(세력 판도·장비 칸 등)은 「?」를 누르면 떠 있는 설명으로 보입니다. 장비 칸에 등급이 보입니다.
- 친구에게 나에게만 보이는 별명과 메모를 붙일 수 있습니다(동료 화면·조사원 카드).
- 이동을 취소한 뒤 다시 떠날 수 있을 때까지 출발 단추가 잠기고 남은 시간이 보입니다.
- 현장 화면에 원정 귀환까지 남은 시간이 보입니다.
- 여기 있는 이들·동료·파티 칸의 얼굴이 채팅과 같은 모양으로 보입니다.
- 파티 원정으로 함께 떠난 동료와 서로 돕는 짧은 줄이 일지에 가끔 나옵니다.
- 테마 「셈판」·「흑백셈판」을 더했습니다.
- 테마·글자 크기·소리 설정이 계정에 저장되어, 새 브라우저나 다른 기기에서도 그대로 따라옵니다.
