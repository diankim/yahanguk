-- 7.2.8 패치노트(7.2.0 본문 끝에 덧붙임, 공지 없이). 장야·마지막 토벌·롤백 절차는 적지 않는다(사용자 결정).
update public.world_patch_notes set body = body || $n$
## 7.2.8
- 회원가입 화면에 초대권 번호 칸을 두었습니다. 이미 계정이 있는 분은 지금처럼 그대로 로그인합니다.
- 설정 › 계정과 캐릭터 만들기 화면에서 내가 받은 초대권 번호와 쓰였는지를 볼 수 있습니다.
- 회원가입·로그인 화면의 안내 문구를 다듬었습니다.
$n$ where note_id = '7.2.0' and position('## 7.2.8' in body) = 0;
