## 7.3.2
- 영역마다 배경음악을 새로 편성했습니다. 선율만이 아니라 빠르기·박자·쓰는 악기·반주·북 장단·곡 구성이 영역마다 다릅니다.
  - 직할령: 대금 주제를 가야금이 따라 부르고, 절정에서 가야금과 대금이 겹치는 위엄 있는 곡
  - 수향: 플루트와 가야금이 주고받는 3박 춤곡
  - 북령: 피아노와 첼로가 주고받는 느린 애가
  - 남명: 빠른 장단 위로 대금이 내달리고 가야금이 굴리는 신명 나는 곡
  - 변경: 현악 받침과 북 행진 위의 해금 주제
  - 지하: 낮은 피아노와 심장 박동 같은 북 위로 대금이 흐르는 음산한 곡
  - 천문: 피아노·하프·종이 반짝이는 맑은 곡
  - 심연: 피아노만으로 부르는 느린 단조 탱고 애가(전투도 같은 결로 조금 더 앞으로)
  - 귀허도: 첼로가 이끌고 현악이 받으며 하프가 뜯는 단조 탱고 애가(전투도 같은 결)
- 전투 음악은 영역마다 따로 편성했습니다(북령은 현악·첼로·종의 진혼곡, 남명은 빠른 장단 등). 큰북이 둥— 하고 깔려 무게를 잡고, 장단은 마디마다 바뀌다 프레이즈 끝에서 몰아칩니다.
- 길게 끄는 관악·현악에 숨결(여리게 들어가 부풀었다 잦아듦)과 떨림을 넣고, 프레이즈 안에서 세기가 오르내리게 했습니다. 화음에 어긋나던 음을 고쳐 더 매끄럽게 들립니다.
- 별채 「한 지붕」: 혼례를 올린 정인과 별채 하나를 함께 쓸 수 있습니다. 한 사람이 둘 중 한 별채를 골라 제안하고 정인이 받으면, 넓이는 그대로지만 설치할 수 있는 가구·곳간·같은 가구 상한이 두 사람 몫이 됩니다. 다른 별채는 지우지 않고 보관하며, 「각자 별채로 돌아가기」나 연리가 끝나면 정인이 들여온 가구는 정인의 곳간으로 돌아갑니다. (캐릭터 › 별채)
