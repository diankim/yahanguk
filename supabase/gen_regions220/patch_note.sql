## 새 세력 지역 일곱
세력마다 바깥 지역을 여섯 곳으로 맞추고, 레벨 구간(1~5·6~10·11~15·16~20·21~29)마다 그 세력 땅이 하나 이상 있게 새 지역 일곱 곳이 열립니다.

### 새 지역
- 「연등 하수도」 Lv7 · 흑련회 — 등잔골 뒷골목·만인장·지맥의 뿌리와 이어진 도성 아래 하수 물길. 수로 낚시터가 있습니다.
- 「흑련 장부고」 Lv18 · 흑련회 — 십삼문 암시장·지맥의 뿌리와 이어진 지하 서고.
- 「서리솔 고개」 Lv8 · 북령맹 — 설피골·빙혼곡과 이어진 솔숲 고개.
- 「천년 빙하」 Lv27 · 북령맹 — 천경호·뇌명봉과 이어진 북녘 끝 얼음 벌판. 얼음 틈 낚시터가 있습니다.
- 「옛 순라청」 Lv12 · 야행국 정통파 — 귀죽림·옛 의금부 옥사·십삼문 암시장과 이어진 옛 관청 터.
- 「핏빛 모래바다」 Lv17 · 적월교 — 유리협곡·적월 제단터와 이어진 서쪽 끝 모래언덕.
- 「잠든 포구」 Lv19 · 수향연맹 — 용잠 수궁·만조의 갑문과 이어진 바다 포구. 바다 낚시터가 있습니다.

### 레벨이 바뀐 지역
- 「구름 위 회랑」(천명원) Lv16 → Lv23. 답사 지점·채집터·원정지·요괴와 그 지역 보조 퀘스트가 같은 만큼 오릅니다.
- 「적사 황무지」(적월교) Lv6 → Lv5. 답사 지점·채집터·원정지·요괴와 그 지역 보조 퀘스트가 같은 만큼 내려갑니다.
- 「혈엽림」(남명회) Lv12 → Lv18. 답사 지점·채집터·원정지·요괴와 그 지역 보조 퀘스트가 같은 만큼 오릅니다.
- 그래서 주 이야기 5장 「이름 없는 종」의 무대 한 곳이 주혈 광산으로 바뀝니다(갱도 원령 셋 잠재우기, 단서 「갱도 속의 쇠사슬」). 남명회 3등급 퀘스트는 주혈 광산에서, 연계 「방망이 든 사슴」은 「방망이 문 갈매기」로 재의 해안에서 이어집니다. 레벨 조건은 그대로입니다.

### 지역마다
- 답사 지점·채집터·요괴 다섯·원정지 셋·조사 지점 셋·처음 방문 글·보조 퀘스트 하나가 있습니다.
- 들머리 「어귀의 …」 채집터는 모든 조사원이 처음부터 찾은 것으로 둡니다.
- 지역 레벨이 길을 막으므로 낮은 이웃에서 들어갑니다(연등 하수도는 등잔골 뒷골목, 서리솔 고개는 설피골, 옛 순라청은 귀죽림).

## 내 모습
조사원의 모습을 직접 꾸미고, 옷을 손수 그려 지어 입을 수 있습니다.

### 꾸미기
- 캐릭터 › 「내 모습」 탭에서 머리·눈·입·윗옷·아랫옷·장신구를 고릅니다.
- 「별채에 세우기」를 켜면 내 모습이 별채 안을 걸어 다닙니다. 한 지붕에 사는 정인의 모습도 함께 보입니다.
- 다른 조사원이 내 카드를 열면 온몸 모습이 보입니다.
- 「얼굴로 쓰기」를 누르면 머리 그림이 채팅·목록·카드·상태판 얼굴이 됩니다. 사진을 새로 올리면 사진으로 바뀝니다.

### 옷 얻기
- 옷과 장신구는 물품입니다. 가방에서 「옷장에」를 누르면 옷장에 들어가고, 그 뒤로는 언제든 골라 입을 수 있습니다.
- 처음부터 직업 기본 옷을 입을 수 있고, 옷 스물세 가지를 상점·직조/법구 공예 제작·퀘스트 보상·비무회 우승·「옷 꾸러미」로 얻습니다.
- 「옷 꾸러미」는 원정 완주와 우두머리 토벌에서 가끔 나오고, 풀면 옷 하나가 나옵니다. 다른 직업의 기본 옷도 들어 있습니다.

### 내 도안
- 옷장에 있는 윗옷이나 아랫옷 하나를 틀로 골라 그 안을 칸마다 직접 칠합니다. 명암은 칠한 색에 맞춰 저절로 들어갑니다.
- 한 도안에 색 여덟 가지까지, 색판에서 고르거나 색 고르기 창으로 직접 정합니다. 단추·띠 같은 장식 색도 따로 바꿀 수 있습니다.
- 아랫옷은 한 번 그리면 걷는 모습에도 그대로 옮겨집니다.
- 새 도안은 하루 두 장까지, 도안첩에는 받은 사본까지 스무 장까지 둡니다. 지운 도안은 「지운 도안」에서 되살릴 수 있습니다.
- 그린 도안은 직조로 지어야 입을 수 있습니다. 윗옷은 저고리, 아랫옷은 치마 제작법과 같은 재료(영사·운면)가 들고, 가방과 창고(안전지대)의 재료를 씁니다.
- 내가 그린 도안은 친구에게 사본으로 보낼 수 있습니다(그림 액자와 같은 하루 횟수). 받은 사람도 직조로 지어 입습니다.
- 도안은 사고팔 수 없습니다.
- 부적절한 도안은 도안첩에서 제보할 수 있고, 운영진이 내린 도안은 모든 사본과 함께 사라집니다.
