## 3.3.0

- 「연담」이 생겼습니다. 이야기에서 만난 인물 열한 명이 저마다 맡은 제작·채집 분야(채취·채광·낚시·단조·목공·법구 공예·봉인 공예·직조·가죽 공예·연금·요리)의 물품을 하루에 셋씩 청합니다. 넘기면 그 분야 숙련 경험과 전을 조금 받고, 그 인물과의 친밀도가 오릅니다. 우수품으로 넘기면 더 많이 오릅니다.
- 인물마다 처음 만나는 이야기를 마쳐야 연담을 맺을 수 있습니다. 요인록·묵적록·명등기를 어디까지 진행했는지에 따라 열리는 인물이 다릅니다.
- 모든 인물을 합쳐 하루 여섯 번까지 넘길 수 있습니다.
- 친밀도가 다섯 단계로 오를 때마다 그 인물과 둘이서 보내는 이야기가 하나씩 열립니다(인물마다 다섯 편, 모두 쉰다섯 편). 다섯째 이야기를 마치면 그 인물만의 칭호와 가구·옷·장신구를 받습니다.
- 연담 인물은 현장의 「연담」 칸과 일지 › 의뢰의 「연담」 칸에서 볼 수 있습니다. 연담을 여럿 맺으면 받는 칭호도 있습니다.
- 거점 사업과 공동 사업은 다섯 단계를 마친 뒤에도 납품 보상이 줄지 않습니다. 마지막 단계 목표만큼 몫이 찰 때마다 한 바퀴로 세어, 그 바퀴에 힘을 보탠 조사원에게 낙성 떡을 나눕니다. 기념패나 낙관을 아직 받지 못했다면 함께 받습니다. 하루 상한은 그대로입니다.
- 친구 신청을 다른 곳에서 받거나 거절하면 남아 있던 친구 신청 창이 저절로 닫힙니다.
- 칭호를 한꺼번에 여럿 얻으면 알림이 한 줄로 모여 뜹니다.
- 별채에서 탁자 위에 놓는 소품을 탁자 윗면을 눌러 올릴 수 있습니다.
- 기술 창에 예전 계열 이름이 남아 보이던 것을 고쳤습니다.$N$
