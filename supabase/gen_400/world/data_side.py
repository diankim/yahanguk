def npc_key(name):
    return 'q:hws_' + hashlib.md5(name.encode()).hexdigest()[:6]


def lines_of(text, speakers):
    out, task = [], None
    for raw in text.strip().splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith('- 할 일:'):
            task = line[7:].strip()
            continue
        if ': ' in line:
            sp, t = line.split(': ', 1)
            if sp in speakers:
                out.append({'s': speakers[sp], 't': t})
                continue
            if sp in Q.KNOWN or sp in Q.MAIN_NPCS:
                out.append({'s': Q.speaker_key(sp), 't': t})
                continue
        out.append({'s': None, 't': line})
    return out, task


def build():
    speakers = {n: npc_key(n) for n in NPC}
    quests, steps = [], []
    for q in QUESTS:
        quests.append(dict(id=q['id'], cat=q['cat'], title=q['title'], L=L, region=q['region'], after=[OPEN[q['region']]], summary=q['summary'], items=q['items']))
        for k, (goal, need, text) in enumerate(q['steps']):
            lines, _ = lines_of(text, speakers)
            steps.append(dict(quest=q['id'], step=k + 1, title=goal, goal=goal, need=need, lines=lines))
    return quests, steps


def check(errors):
    speakers = {n: npc_key(n) for n in NPC}
    for q in QUESTS:
        st = q['steps']
        for k, (goal, need, text) in enumerate(st):
            lines, task = lines_of(text, speakers)
            if k + 1 < len(st) and not task:
                errors.append(f"보조 {q['id']} 장면 {k + 1}: 할 일 줄 없음")
            if k + 1 == len(st) and task:
                errors.append(f"보조 {q['id']} 마지막 장면에 할 일 줄")
            if k > 0 and not need.get('tasks') and not need.get('give'):
                errors.append(f"보조 {q['id']} 장면 {k + 1}: need에 할 일이 없음")
            for ln in lines:
                if ln['s'] is None and ln['t'][:3] in ('그런데', '그러나', '그러자', '그리고', '하지만'):
                    errors.append(f"보조 {q['id']} 장면 {k + 1}: 서술 첫머리 접속사")
                if any(x in ln['t'] for x in ('형님', '누님', '라는 것이었다', '라고 일렀다')):
                    errors.append(f"보조 {q['id']} 장면 {k + 1}: 금지 표현 — {ln['t'][:20]}")


def emit(fresh, errors, warns, bulk, J, TA, known, RID, REF, xp_need):
    check(errors)
    quests, steps = build()
    fresh('npcs', list(NPC), '인물')
    fresh('quest_ids', [q['id'] for q in quests], '퀘스트 id')
    out = []
    rows = [dict(npc_key=npc_key(n), npc_name=n, bio=b) for n, b in NPC.items()]
    out.append(f"""insert into public.world_quest_npcs(npc_key, npc_name, bio) select x.npc_key, x.npc_name, x.bio from jsonb_to_recordset({J(rows)}) as x(npc_key text, npc_name text, bio text)
on conflict (npc_key) do update set npc_name = excluded.npc_name, bio = excluded.bio;""")
    qrows, srows = [], []
    for i, q in enumerate(quests):
        mine = [s for s in steps if s['quest'] == q['id']]
        tot = round(0.4 * xp_need(q['L']) * 0.25)
        task_steps = [s['step'] for s in mine if s['need'].get('tasks') or s['need'].get('give')]
        per = tot // max(1, len(task_steps))
        qrows.append(dict(quest_id=q['id'], cat=q['cat'], title=q['title'], summary=q['summary'], region_id=q['region'], min_level=q['L'], after=q['after'], sort=1700 + i, epilogue=[]))
        for s in mine:
            rw = {'xp': per} if s['step'] in task_steps else {}
            if s['step'] == len(mine):
                rw['gil'] = 5 + 4 * q['L']
                rw['items'] = q['items']
            for t in s['need'].get('tasks', []):
                for k in t.get('items', []):
                    if k not in known: errors.append(f"보조 {q['id']} 할 일 물품 없음: {k}")
                for rg in t.get('r', []):
                    if rg not in RID: errors.append(f"보조 {q['id']} 지역 없음: {rg}")
            for k in list(s['need'].get('give', {})) + list(rw.get('items', {})):
                if k not in known: errors.append(f"보조 {q['id']} 물품 없음: {k}")
            srows.append(dict(quest_id=q['id'], step=s['step'], title=s['title'], goal=s['goal'], need=s['need'], lines=s['lines'], reward=rw))
    qcols = [('quest_id', 'text'), ('kind', 'text'), ('cat', 'text'), ('title', 'text'), ('summary', 'text'), ('region_id', 'text'), ('min_level', 'int'), ('after', 'jsonb'),
             ('sort', 'int'), ('epilogue', 'jsonb'), ('active', 'boolean')]
    scols = [('quest_id', 'text'), ('step', 'int'), ('title', 'text'), ('goal', 'text'), ('need', 'jsonb'), ('lines', 'jsonb'), ('reward', 'jsonb')]
    for tbl, rows_, cols, conf, upd, conv in (
            ('world_quests', qrows, qcols, 'quest_id', ['cat', 'title', 'summary', 'region_id', 'min_level', 'after', 'sort', 'epilogue', 'active'], {'kind': "'side'", 'after': TA('after'), 'active': 'true'}),
            ('world_quest_steps', srows, scols, 'quest_id, step', ['title', 'goal', 'need', 'lines', 'reward'], {})):
        ins = [c for c, _ in cols]
        sel = ', '.join(conv.get(c, 'x.' + c) for c in ins)
        out.append(f"""insert into public.{tbl}({', '.join(ins)})
select {sel} from jsonb_to_recordset({J(rows_)}) as x({', '.join(c + ' ' + t for c, t in cols)})
on conflict ({conf}) do update set {', '.join(f'{u} = excluded.{u}' for u in upd)};""")
    import sys
    sys.stderr.write(f'보조 퀘스트 {len(qrows)} · 장면 {len(srows)} · 인물 {len(NPC)}\n')
    return '\n'.join(out)
