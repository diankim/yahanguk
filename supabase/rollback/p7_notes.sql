## 직업별 전투 기술
- 전투 기술 경험이 든 무기가 아니라 **직업의 계열**에 쌓입니다. 호위 무사 근접 · 현장 조사원 사격(옛 이름 원거리) · 봉인술사 봉인술에 더해 **퇴마관 퇴마술 · 백공 기술관 단도 · 의무관 의술**이 새로 생겼습니다. 분석·막기·응급 처치는 모두가 함께 씁니다.
- 새 계열의 기본 기술 수치는 전에 쓰던 계열과 같고, 택일 한쪽은 직업 고유의 갈래입니다: 단도 「재주」(급소 해부·독 바른 날·손재주 덫·장인의 눈) · 퇴마술 「정화」(파사안·퇴마 진언·정화의 불·금강 결계) · 의술 「처방」(맥 짚기·보신 처방·해독 처방·회춘). 방패(이목·도발) 갈래는 호위 무사에게만 있습니다.
- 무기는 직업에 맞는 것만 듭니다: 근접 무기 호위 무사·백공 기술관 · 원거리 무기 현장 조사원 · 술법 무기 퇴마관·봉인술사·의무관.
- 조합 기술 「칼집 손질」(단도·가죽 공예) · 「부적 퇴마진」(퇴마술·봉인 공예) · 「약선 처방」(의술·연금), 칭호 「비수의 길」·「퇴마의 길」·「의술의 길」과 숨김 칭호 셋이 더해졌습니다. 「검의 길」·「활의 길」·「술의 길」은 그 직업 계열로 센 토벌입니다.
- **환골탈태 서첩**을 대세력 비고에서 2등급부터 공훈 300으로 살 수 있습니다. 쓰면 레벨·기술 단계·대세력은 그대로, 직업과 소속을 다시 고르고 능력치를 처음으로 돌려 포인트를 돌려받습니다. 지난 직업의 전투 계열은 단계만 남고 효과가 없습니다.

