## 직업 역할
- **호위 무사는 방패·수호**입니다. 받는 피해 −12%·이목 +50으로 요괴의 시선을 끌고 동료를 지킵니다(근접 피해 +8%는 빠졌습니다). 근접 계열 택일은 ① 방패(호령·도발·철갑 강기·사자후) ② 수호(반격 자세·버팀 기세·불굴·수호신), 숙달 「금강 수호」. 협동 기술은 패턴 공유·대신 막기·흐름 끊기·철벽 수호.
- **근접 공격수는 백공 기술관**입니다. 근접 피해 +8%·근접 치명타 +5가 붙고, 단도 계열에 근접 공격 기술이 모였습니다. 원정 기술은 「급소 찌르기」(싸울 때마다 25% 확률로 승률 +10%p).
- **직업 효과는 모두 전투 쪽**입니다. 백공 기술관의 생활 효과(채집량·희귀품·제작 품질·강화 확률·다른 직업 전용 제작법·원정 현장 가공)는 없어졌고, 채집·제작은 직업과 상관없이 누구나 같은 조건입니다.
- **퇴마관은 술법 공격**에 집중합니다. 협동 기술은 약점 진언·파사 진언·퇴마 결계·멸마 진격(지키기 기술은 호위 무사에게 넘겼습니다).
- **현장 조사원은 원거리 공격**에 맞췄습니다. 원정 기술은 「흔적 추적」(싸움 피하기) 대신 「선제 사격」(싸울 때마다 30% 확률로 승률 +12%p)이고, 원정 채집 +15%·발견 덤·탐색 길/채집터 덤은 없어졌습니다.
- **의무관은 치유**에 맞췄습니다. 의술 계열 기본 기술이 회복 중심이 되어 50단계까지 회복량 +35%(술법 피해는 +17%).
- 직업을 고르는 화면과 도움말에 직업마다 역할이 적혀 있습니다: 호위 무사 방패·수호 · 현장 조사원 원거리 공격 · 퇴마관 술법 공격 · 백공 기술관 근접 공격 · 의무관 치유 · 봉인술사 보조(북돋기·약화).

## 직업별 전투 기술
- 전투 기술 경험이 든 무기가 아니라 **직업의 계열**에 쌓입니다. 호위 무사 근접 · 현장 조사원 사격(옛 이름 원거리) · 봉인술사 봉인술에 더해 **퇴마관 퇴마술 · 백공 기술관 단도 · 의무관 의술**이 새로 생겼습니다. 분석·막기·응급 처치는 모두가 함께 씁니다.
- 새 계열의 기본 기술 수치는 전에 쓰던 계열과 같고, 택일 한쪽은 직업 고유의 갈래입니다: 단도 「재주」(급소 해부·독 바른 날·손재주 덫·장인의 눈) · 퇴마술 「정화」(파사안·퇴마 진언·정화의 불·금강 결계) · 의술 「처방」(맥 짚기·보신 처방·해독 처방·회춘). 방패(이목·도발) 갈래는 호위 무사에게만 있습니다.
- 무기는 직업에 맞는 것만 듭니다: 근접 무기 호위 무사·백공 기술관 · 원거리 무기 현장 조사원 · 술법 무기 퇴마관·봉인술사·의무관.
- 조합 기술 「칼집 손질」(단도·가죽 공예) · 「부적 퇴마진」(퇴마술·봉인 공예) · 「약선 처방」(의술·연금), 칭호 「비수의 길」·「퇴마의 길」·「의술의 길」과 숨김 칭호 셋이 더해졌습니다. 「검의 길」·「활의 길」·「술의 길」은 그 직업 계열로 센 토벌입니다.
- 직업마다 무기를 따로 챙기게 되어 **가방 기본 34칸(전 24)**, **창고 기본 70칸(전 60, 최대 108)**으로 늘었습니다.
