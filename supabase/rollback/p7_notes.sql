## 직업 역할
- **호위 무사는 방패·수호**입니다. 받는 피해 −12%·이목 +80으로 요괴의 시선을 끌고 동료를 지킵니다. 방패를 든 만큼 공격력은 ×0.85입니다. 근접 계열 택일은 ① 방패(호령·도발·철갑 강기·사자후) ② 수호(반격 자세·버팀 기세·불굴·수호신), 숙달 「금강 수호」. 협동 기술은 패턴 공유·대신 막기·흐름 끊기·철벽 수호.
- **직업 이름이 바뀌었습니다.** 백공 기술관 → 「암영 검객(暗影劍客)」(그림자에서 요괴의 급소를 끊는 검객), 현장 조사원 → 「월궁 사수(月弓射手)」(달빛 아래 먼 곳을 쏘는 사수).
- 암영 검객의 협동 기술이 근접 공격 기술로 바뀌었습니다: 그림자 찌르기(다음 공격 치명타) · 급소 드러내기(요괴가 받는 피해 +15% 세 번) · 그림자 숨기(회피 +40% 두 번) · 암영 난무(제 공격 세 번 +40%).
- **봉인술사는 보조·버팀**입니다. 동료를 북돋고 요괴를 묶는 한편 술사 가운데 가장 단단해(이목 +60·방어 +30·회피 +12), 앞줄이 비면 받쳐 냅니다. **퇴마관**은 몸은 약하지만 이목이 낮아(−15) 뒷줄에서 술법을 쏟습니다.
- **근접 공격수는 암영 검객**입니다. 근접 공격력 ×1.18(피해 상한과 따로)·근접 치명타 +5가 붙고, 단도 계열에 근접 공격 기술이 모였습니다. 단도 기본 기술 넷이 이목을 낮춰(합 −45%) 요괴 눈에 덜 띕니다. 기본 능력치는 근력 8·민첩 6·체질 5·감각 5. 원정 기술은 「급소 찌르기」(싸울 때마다 25% 확률로 승률 +10%p).
- **직업 효과는 모두 전투 쪽**입니다. 암영 검객의 생활 효과(채집량·희귀품·제작 품질·강화 확률·다른 직업 전용 제작법·원정 현장 가공)는 없어졌고, 채집·제작은 직업과 상관없이 누구나 같은 조건입니다.
- **퇴마관은 술법 공격**에 집중합니다. 협동 기술은 약점 진언·파사 진언·퇴마 결계·멸마 진격(지키기 기술은 호위 무사에게 넘겼습니다).
- **월궁 사수는 원거리 공격**에 맞췄습니다. 원정 기술은 「흔적 추적」(싸움 피하기) 대신 「선제 사격」(싸울 때마다 30% 확률로 승률 +12%p)이고, 원정 채집 +15%·발견 덤·탐색 길/채집터 덤은 없어졌습니다.
- **의무관은 치유**에 맞췄습니다. 의술 계열 기본 기술이 회복 중심이 되어 50단계까지 회복량 +35%(술법 피해는 +17%).
- 직업을 고르는 화면과 도움말에 직업마다 역할이 적혀 있습니다: 호위 무사 방패·수호 · 월궁 사수 원거리 공격 · 퇴마관 술법 공격 · 암영 검객 근접 공격 · 의무관 치유 · 봉인술사 보조·버팀(북돋기·약화, 이목·방어는 호위 무사 다음).

## 보스 싸움 균형
- 직업의 힘은 현장 토벌·혼자 원정·귀허의 주인·구중 봉주 결전·봉연의 그림자 다섯 곳을 함께 재며 맞췄습니다(현장에서만 강하고 보스에서 약한 직업이 없게).
- 퇴마관: 술법 치명타 +6, 받는 피해 −6%. 호위 무사 수호 「버팀 기세」는 다음 공격 +20%.
- 구중 봉주 결전: 술법 공격이 영력 2만 씁니다. 모두 물러나 있을 때 보스가 되찾는 체력 1.5%, 보스가 주는 피해 ×0.8, 체력 배율 혼자 2.4·둘 3.3배. 귀허의 주인 혼자는 체력 1.2배. 결전에만 붙던 퇴마관·봉인술사 피해 +25%는 없앴습니다.
- 혼자 도전 보정은 남은 차이만 작게 남겼습니다(도움말 「혼자 도전할 때의 직업 보정」).

## 직업별 전투 기술
- 전투 기술 경험이 든 무기가 아니라 **직업의 계열**에 쌓입니다. 호위 무사 근접 · 월궁 사수 사격(옛 이름 원거리) · 봉인술사 봉인술에 더해 **퇴마관 퇴마술 · 암영 검객 단도 · 의무관 의술**이 새로 생겼습니다. 분석·막기·응급 처치는 모두가 함께 씁니다.
- 새 계열의 기본 기술 수치는 전에 쓰던 계열과 같고, 택일 한쪽은 직업 고유의 갈래입니다: 단도 「암습」(급소 해부·독 바른 날·그림자 덫·꿰뚫는 눈) · 퇴마술 「정화」(파사안·퇴마 진언·정화의 불·금강 결계) · 의술 「처방」(맥 짚기·보신 처방·해독 처방·회춘). 방패(이목·도발) 갈래는 호위 무사에게만 있습니다.
- 무기는 직업에 맞는 것만 듭니다: 근접 무기 호위 무사·암영 검객 · 원거리 무기 월궁 사수 · 술법 무기 퇴마관·봉인술사·의무관.
- 조합 기술 「칼집 손질」(단도·가죽 공예) · 「부적 퇴마진」(퇴마술·봉인 공예) · 「약선 처방」(의술·연금), 칭호 「비수의 길」·「퇴마의 길」·「의술의 길」과 숨김 칭호 셋이 더해졌습니다. 「검의 길」·「활의 길」·「술의 길」은 그 직업 계열로 센 토벌입니다.
- 직업마다 무기를 따로 챙기게 되어 **가방 기본 34칸(전 24)**, **창고 기본 70칸(전 60, 최대 108)**으로 늘었습니다.
