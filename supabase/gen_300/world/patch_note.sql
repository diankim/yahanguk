### 백야
- 등도에는 밤이 오지 않습니다. 흰 하늘 아래 있는 동안 정신 손실·받는 피해·요괴 조우가 조금 늘고, 대신 그림자가 없어 기척 숨기기·조용히 살피기·회피가 조금 쉬워집니다.
- **불러 줄 이 없음:** 등도에서 쓰러지면 본부 구조대가 오지 못합니다. 같은 곳 조사원의 구조나 회생 부적, 또는 하루 한 번 「제 이름 외기」로 가장 가까운 등도 안전지대에서 일어날 수 있습니다. 쓰러진 지 4시간이 지나도록 일어나지 못하면 숨집니다. 등도 현장 맨 위 띠에 늘 적혀 있습니다.
- 명등 등롱을 켜면 한동안 백야를 받지 않습니다. 그 구역의 장을 마치면 그 구역의 밤을 되찾아 백야가 걷힙니다.

