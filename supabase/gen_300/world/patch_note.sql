### 퀘스트 다시하기
- 마친 퀘스트는 일지의 마친 카드에서 「다시하기」로 처음부터 다시 겪을 수 있습니다. 경험치·물품 보상은 없고, 다 마치면 그 퀘스트 전 보상의 일부를 받습니다. 한 번에 세 편까지 할 수 있고, 처음 마친 기록·칭호는 그대로입니다.

### 세력 거점 사업
- 대세력마다 거점을 함께 다시 세우는 사업이 열립니다. 가입 퀘스트를 마친 조사원이 거점에서 정한 제작품·채집 재료를 넘기고, 넘긴 몫만큼 공훈을 받습니다. 캐릭터 › 세력 「거점 사업」이나 거점 현장의 띠에서 엽니다.
- 단계마다 받는 물품 여덟 가지 중 둘이 날마다 「급히 필요」로 바뀌어 몫이 늘고, 우수품도 몫이 늡니다. 급히 필요한 채집 재료는 현장 채집터에 「사업」 칩이 붙습니다. 한 사람이 하루에 넘길 수 있는 몫은 거점·공동·남의 세력 사업을 모두 합쳐 정해져 있습니다.
- 단계 목표는 모든 세력이 같고, 한 번 찬 단계는 그대로 남습니다.
- 다른 세력 조사원과 대세력이 없는 조사원도 그 세력 거점에서 사업을 도울 수 있습니다. 돕는 몫은 그 세력 단계에 쌓이고 보상은 전으로 받으며, 단계가 찰 때 낙성 떡과 사업 칭호에도 셉니다. 단계 혜택은 그 세력 조사원만 누립니다. 내 세력이 있으면 도울 때 두 세력의 관계가 조금씩 오릅니다.
- 다섯 단계를 차례로 채우면 그 세력 조사원에게 거점 상점 새 품목 → 거점과 이웃 지역 효과 → 거점과 본래 땅 사이 지름길 → 비고 새 품목 → 세력 바탕 무늬와 거점 풍경이 열립니다.
- 단계가 차는 순간 그 단계에 힘을 보탠 조사원은 낙성 떡(그 세력 조사원은 공훈도)을, 마지막 단계에는 기념 가구를 받습니다. 넘긴 몫의 누계로 얻는 「사업」 칭호가 있습니다.
- 모든 세력 비고에 같은 공통 품목(가구·옷·노정패 묶음·동무 새참·알·머리 그리기 도안)이 사업 단계에 따라 하나씩 열립니다.

### 공동 사업
- 반요촌·묵창 나루·남문 수로 선착과 등지기 쉼막에 모든 조사원이 함께 채우는 공동 사업이 열립니다. 그 땅이 열린 조사원은 누구나 그 땅 재료와 그 땅 재료로 만든 것을 넘기고, 넘긴 몫만큼 전을 받습니다.
- 단계마다 빈약한 안전지대의 막힌 것이 하나씩 풀립니다: 상점 품목 → 지름길 → 창고 → 거래소·마구간 → 수리비·되팔기·대장간이 바깥과 같아지고 풍경이 바뀜. 풀린 것은 그 땅 이야기를 마친 조사원만 누리고, 마치지 않은 조사원에게는 그대로입니다(상점 품목 수가 느는 것은 모두에게).
- 단계가 차면 전체 채팅 「사업 소식」으로 알립니다.

### 그 밖
- 동승 요청을 받은 파티원이 수락하거나 사양하면, 요청한 사람에게도 알림이 가고 이동 띠가 바로 뜹니다.
- 등도 가구·칭호·꾸미기가 들어옵니다.
- 가방에서 옷·옷 꾸러미 줄에 「옷장에」·「풀기」 단추가 바로 보입니다.
- 퀵슬롯 칸 바꾸기가 물품 고르기 창으로 바뀌었습니다. 다른 칸에 이미 넣은 물품은 「n번 칸에 있음」으로 표시되고 목록 뒤로 갑니다.
- 정인에게 보내는 하루 선물도 서신처럼 물품 고르기 창으로 고릅니다.
- 지도의 예상 이동 시간과 운임이 서버 경로 그대로 나옵니다(사업 지름길이 있으면 「운임 없음」).
- 지도에서 빈약한 안전지대에 「빈약한 안전지대」가 적힙니다.
- 일지 이야기 단추에 마친 장 수가, 진행 중 카드에 「보고만 남음」·「다시하는 중」이 적힙니다.
- 본편 1~10장과 외전 「요인록」의 대사·서술을 다듬었습니다. 할 일·보상은 그대로이고, 세력 거점 장면에서는 그 세력 조사원에게 첫인사가 달라집니다(퀘스트 다시하기로 다시 볼 수 있습니다).

