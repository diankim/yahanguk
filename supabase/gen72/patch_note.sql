## 별채(別棟)
- 본부 객사 뒤뜰의 빈 별채를 내 방으로 꾸밉니다. 효과는 없고 꾸미기·구경·방명록을 즐기는 곳입니다(캐릭터 › 별채, 조사원 카드의 「별채 구경」).
- **열기**: 주 이야기 4장을 마치고 Lv15가 되면 본부 객사의 살림꾼 보미에게서 「객사 별채」를 받습니다. 부적목·황지를 채집하고 오방색 방석을 만든 뒤 수리비 1,000전을 치르면 6×6 별채와 기본 세트 「단청 별채」를 받습니다.
- **넓히기**: 6×6(가구 15개) → 7×7(20) → 8×8(26, Lv20) → 9×9(32, Lv25). 전과 목재가 듭니다.
- **가구 69가지**: 바닥 가구·깔개·소품(탁자 위에 올림)·벽 장식·창문·문·벽지·바닥재. 등급이 높을수록 크고 화려합니다. 같은 가구는 범품 4 · 양품 3 · 진품 2 · 명품·신품 1개까지 놓습니다.
- 가구는 가방에 들어오는 물품이고, 놓으면 가방에서 빠집니다. 거두면 **곳간**(30칸, 넓힐 때마다 +5)으로 가고, 곳간에서 꺼내면 가방으로 돌아옵니다.
- 놓기·옮기기·곳간 넣기·꺼내기·넓히기는 안전지대에서만, 구경과 곳간에서 버리기는 어디서나 됩니다.
- 곳간이 가득 찬 채 토벌·원정에서 가구를 얻으면 가방으로 들어옵니다(가방도 차면 두고 오고 알려 드립니다).
- 기본 세트 「단청 별채」의 가구·벽지·바닥재는 본부 상점에서 늘 팝니다. 잃어버려도 다시 들일 수 있습니다.
- **얻는 곳**: 상점·제작(목공·직조·법구 공예·봉인 공예·단조)·토벌 전리품·우두머리·원정 완주·세력 비고, 그리고 이야기 6~10장·칭호·봉연의 그림자·10장 결전·귀허의 주인·비무회·혼례 보상. 조건을 채워 얻은 가구는 거래·상점 판매가 안 되고 세력 기부는 됩니다. 이미 마친 장·칭호의 가구는 곳간에 넣어 드렸습니다.
- **대문**(활짝 엶·벗에게만·닫음), **방명록**(한 줄 80자, 하루 3개, 최근 20개), **발걸음**(오늘·전체).
- 혼례를 올린 정인은 서로의 별채를 꾸밀 수 있습니다(한 지붕).

## 꼬마 동무
- 별채에서 함께 사는 작은 동무 30종입니다. 능력치 효과는 없고 모으고 보여 주는 즐거움입니다.
- 범품은 상점의 바구니, 양품은 탐색 중 드물게 줍는 「얼룩무늬 알」, 진품은 퀘스트와 아주 드문 「빛나는 알」, 명품은 어려운 퀘스트·칭호, 신품은 아주 어려운 칭호와 귀허의 주인 첫 처치로 만납니다. 이미 마친 퀘스트·칭호의 동무는 도감에 넣어 드렸습니다.
- 별채에 한 마리를 두면 방을 돌아다니며 방석에서 자고 그릇·놀잇감에 들릅니다. 「데리고 다니기」를 하면 조사원 카드에 함께 보입니다.
- 쓰다듬기·놀아 주기·먹이 주기로 친밀도가 오르고 100이 되면 다 자랍니다. 손님도 하루 한 번씩 쓰다듬고 놀아 줄 수 있습니다.
- 먹이는 동무 주먹밥 10전(상점에 늘 있음)과 별미 다섯(30~50전). 안 먹여도 불이익은 없습니다. 별명은 8자까지.
- 별채·동무 칭호 12가지와 꾸미기 셋(처마 끝 테·단청 무늬·낙관 「同」)이 생겼습니다.

