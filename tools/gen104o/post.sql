- 기여도를 공격·버팀·치유·북돋움 네 갈래로 나누어, 갈래마다 각자 차지한 몫을 따로 잰 뒤 합칩니다. 방패는 버팀에서, 의무관은 치유에서, 북돋는 직업은 북돋움에서 1등을 노릴 수 있습니다.
