/* ── 그리기: 생성 화면의 자세히 칸과 도움말이 같은 글을 쓴다 ─────────── */
const STAT_KO = { strength: '힘', agility: '민첩', vitality: '체질', perception: '감각', willpower: '의지', spirit_affinity: '영기' };
export const baseText = b => Object.entries(b).sort((x, y) => y[1] - x[1]).map(([k, v]) => `${STAT_KO[k]} ${v}`).join(' · ');
const row = (k, v) => v ? `<div class="lore-row"><b>${k}</b><span>${v}</span></div>` : '';
export function jobLoreHtml(key) {
  const j = JOBS[key], l = JOB_LORE[key]; if (!j || !l) return '';
  return `<article class="lore-card">
    <header><strong>${esc(j.name)}</strong><span class="lore-hanja">${esc(l.hanja)}</span><span class="tag">${esc(j.trait)}</span></header>
    <p class="lore-motto">「${esc(l.motto)}」</p>
    ${l.story.map(p => `<p>${esc(p)}</p>`).join('')}
    <div class="lore-rows">
      ${row('전투', esc(l.fight))}${row('원정', esc(l.road))}${row('무기', esc(l.weapon))}
      ${row('유리한 요괴', esc(l.good.join('·')) + (l.weak.length ? ` <small class="muted">/ 덜 듣는 요괴 ${esc(l.weak.join('·'))}</small>` : ''))}
      ${row('어울리는 사람', esc(l.fits))}${row('조심할 점', esc(l.hard))}${row('인연', esc(l.ties))}
      ${row('직업 효과', esc(j.desc))}${row('기본 능력치', esc(baseText(j.base)))}${row('시작 장비', esc(j.kit))}
    </div></article>`;
}
